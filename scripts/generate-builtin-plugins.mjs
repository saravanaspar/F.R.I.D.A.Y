import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const configPath = resolve(root, "friday.config.json");
const outputPath = resolve(root, "src", "builtin-plugins.ts");
const check = process.argv.includes("--check");
const config = JSON.parse(await readFile(configPath, "utf8"));
if (!Array.isArray(config.plugins) || config.plugins.length === 0) throw new Error("friday.config.json must contain plugins[]");

function identifier(path, index) {
  const segment = path.split("/").filter(Boolean).at(-2) ?? `plugin-${index}`;
  const name = segment.replace(/-([a-z0-9])/g, (_match, char) => char.toUpperCase()).replace(/[^A-Za-z0-9_$]/g, "");
  return /^[A-Za-z_$]/.test(name) ? name : `plugin${index}`;
}

const seen = new Set();
const entries = config.plugins.map((path, index) => {
  if (typeof path !== "string" || !/^\.\/plugins\/[A-Za-z0-9._/-]+\/index\.ts$/.test(path)) throw new Error(`Unsupported builtin plugin path: ${String(path)}`);
  if (seen.has(path)) throw new Error(`Duplicate builtin plugin path: ${path}`);
  seen.add(path);
  return { path, name: identifier(path, index), importPath: `../${path.slice(2, -3)}.js` };
});
const names = new Set();
for (const entry of entries) {
  if (names.has(entry.name)) throw new Error(`Builtin plugin identifier collision: ${entry.name}`);
  names.add(entry.name);
}

const output = [
  "// GENERATED by scripts/generate-builtin-plugins.mjs from friday.config.json. Do not edit manually.",
  'import type { FridayPlugin } from "./plugin.js";',
  ...entries.map((entry) => `import ${entry.name} from ${JSON.stringify(entry.importPath)};`),
  "",
  "/** Ordered exactly like friday.config.json; Map insertion order is startup order. */",
  "export const BUILTIN_PLUGINS: ReadonlyMap<string, FridayPlugin> = new Map([",
  ...entries.map((entry) => `  [${JSON.stringify(entry.path)}, ${entry.name}],`),
  "]);",
  "",
].join("\n");

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error("src/builtin-plugins.ts is out of date; run npm run generate:builtin-plugins");
    process.exitCode = 1;
  } else {
    console.log("Builtin plugin registry check: PASS");
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Generated ${entries.length} builtin plugin imports.`);
}
